def execute_failback(config, state, force=False):
    """
    Execute the complete failback sequence.
    
    Flow:
    1. Pre-flight checks
    2. Pause auto-failover
    3. Stop app on DR (keep PG running)
    4. Sync data DR → Primary
    5. Start primary
    6. Verify primary health
    7. Convert DR back to standby
    8. Resume auto-failover monitoring
    """
    primary = config["primary"]
    dr = config["dr"]
    ssh_user = primary.get("ssh_user", "ubuntu")
    ssh_host = primary["ssh_host"]
    ssh_key = primary.get("ssh_key", "")
    compose_path = dr["compose_path"]
    primary_compose = primary.get("compose_path", "/home/ubuntu/devops-learning-web")

    total_steps = 10

    banner("FAILBACK — DR → PRIMARY", "🔄")
    log.critical("🔄 ═══ FAILBACK INITIATED ═══")
    state.add_history("FAILBACK_STARTED")

    print(f"  {C.BOLD}Primary:{C.END}  {ssh_host}")
    print(f"  {C.BOLD}DR:{C.END}       {dr['instance_id']}")
    print(f"  {C.BOLD}Time:{C.END}     {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}")

    # ── Step 1: Pre-flight ──
    step(1, total_steps, "Pre-flight checks")
    passed, results = preflight_checks(config, state)
    if not passed and not force:
        result_fail("Pre-flight failed — use --force to override")
        return False

    if not force:
        print(f"\n  {C.YELLOW}{C.BOLD}⚠️  FAILBACK WILL:{C.END}")
        print(f"  {C.YELLOW}  • Stop the app on DR server{C.END}")
        print(f"  {C.YELLOW}  • Sync ALL data from DR → Primary{C.END}")
        print(f"  {C.YELLOW}  • Restart primary as the main database{C.END}")
        print(f"  {C.YELLOW}  • Convert DR back to standby mode{C.END}")
        if not confirm("Proceed with failback?"):
            print("❌ Failback cancelled")
            return False

    # ── Step 2: Pause auto-failover ──
    step(2, total_steps, "Pausing auto-failover daemon")
    state.set_status("FAILBACK_IN_PROGRESS")
    state.add_history("AUTO_FAILOVER_PAUSED_FOR_FAILBACK")
    result_pass("Auto-failover paused")

    # ── Step 3: Stop app on DR (keep PG for data sync) ──
    step(3, total_steps, "Stopping app on DR (keeping PostgreSQL)")
    ok, out, err = run_cmd([
        "sudo", "docker", "rm", "-f",
        "devops-learning-app", "devops-learning-nginx"
    ], timeout=30)
    if ok:
        result_pass("App and Nginx stopped on DR")
    else:
        result_warn(f"Some containers may not exist: {err}")

    # ── Step 4: Stop primary PostgreSQL ──
    step(4, total_steps, "Stopping primary PostgreSQL")
    ok, out, err = run_remote(
        ssh_host, ssh_user, ssh_key,
        "docker stop devops-learning-app devops-learning-db-prod devops-learning-nginx 2>/dev/null; echo DONE"
    )
    if ok:
        result_pass("Primary containers stopped")
    else:
        result_warn(f"Primary stop: {err}")

    # ── Step 5: Get PG data path on primary ──
    step(5, total_steps, "Finding primary PG data path")
    ok, pg_path, err = run_remote(
        ssh_host, ssh_user, ssh_key,
        "docker volume inspect devops-learning-web_pg_data --format '{{ .Mountpoint }}' 2>/dev/null || echo '/var/snap/docker/common/var-lib-docker/volumes/devops-learning-web_pg_data/_data'"
    )
    if ok and pg_path:
        result_pass(f"Primary PG path: {pg_path}")
    else:
        pg_path = "/var/snap/docker/common/var-lib-docker/volumes/devops-learning-web_pg_data/_data"
        result_warn(f"Using default path: {pg_path}")

    # ── Step 6: Sync data from DR → Primary via pg_dump/pg_restore ──
    step(6, total_steps, "Syncing data from DR → Primary")
    print(f"  {C.YELLOW}This may take several minutes...{C.END}")

    # Strategy: pg_dump on DR (local) → SCP to primary → restore
    # This is more reliable than pg_basebackup across firewalls

    # 6a: Dump the database on DR (local Docker)
    print(f"  {C.YELLOW}  6a. Dumping database on DR...{C.END}")
    ok1, dump_out, dump_err = run_cmd([
        "sudo", "docker", "exec", "devops-learning-db-dr",
        "pg_dumpall", "-U", "devops", "--clean", "--if-exists",
        "-f", "/tmp/failback_dump.sql"
    ], timeout=300)

    if not ok1:
        result_fail(f"pg_dumpall failed: {dump_err}")
        state.set_status("FAILED")
        return False
    result_pass("Database dumped on DR")

    # 6b: Copy dump file from Docker container to host
    print(f"  {C.YELLOW}  6b. Extracting dump from container...{C.END}")
    run_cmd("sudo docker cp devops-learning-db-dr:/tmp/failback_dump.sql /tmp/failback_dump.sql", timeout=60)
    ok_size, size_out, _ = run_cmd("ls -lh /tmp/failback_dump.sql | awk '{print $5}'", timeout=5)
    if ok_size:
        result_pass(f"Dump file size: {size_out.strip()}")

    # 6c: SCP dump to primary server
    print(f"  {C.YELLOW}  6c. Copying dump to primary server...{C.END}")
    scp_cmd = ["scp", "-o", "StrictHostKeyChecking=no", "-o", "BatchMode=yes"]
    if ssh_key:
        scp_cmd.extend(["-i", ssh_key])
    scp_cmd.extend(["/tmp/failback_dump.sql", f"{ssh_user}@{ssh_host}:/tmp/"])
    ok2, _, scp_err = run_cmd(scp_cmd, timeout=300)
    if not ok2:
        result_fail(f"SCP to primary failed: {scp_err}")
        state.set_status("FAILED")
        return False
    result_pass("Dump copied to primary")

    # 6d: Start primary PostgreSQL container (fresh)
    print(f"  {C.YELLOW}  6d. Starting primary PostgreSQL...{C.END}")
    run_remote(ssh_host, ssh_user, ssh_key,
               f"cd {primary_compose} && "
               "docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d postgres",
               timeout=60)
    # Wait for PG to be ready
    pg_ready = False
    for attempt in range(1, 13):
        ok_ready, ready_out, _ = run_remote(
            ssh_host, ssh_user, ssh_key,
            "docker exec devops-learning-db-prod pg_isready -U devops -d devops_learning 2>/dev/null"
        )
        if ok_ready and "accepting" in ready_out:
            pg_ready = True
            break
        time.sleep(5)
    if not pg_ready:
        result_fail("Primary PostgreSQL failed to start")
        state.set_status("FAILED")
        return False
    result_pass("Primary PostgreSQL is running")

    # 6e: Copy dump into container and restore
    print(f"  {C.YELLOW}  6e. Restoring database on primary...{C.END}")
    run_remote(ssh_host, ssh_user, ssh_key,
               "docker cp /tmp/failback_dump.sql devops-learning-db-prod:/tmp/failback_dump.sql",
               timeout=60)
    ok3, restore_out, restore_err = run_remote(
        ssh_host, ssh_user, ssh_key,
        "docker exec devops-learning-db-prod psql -U devops -d postgres "
        "-f /tmp/failback_dump.sql 2>&1 | tail -5",
        timeout=300
    )
    if ok3:
        result_pass("Database restored on primary!")
        log.info(f"Restore output: {restore_out}")
    else:
        result_fail(f"Restore failed: {restore_err}")
        state.set_status("FAILED")
        return False

    # Cleanup dump files
    run_cmd("sudo rm -f /tmp/failback_dump.sql", timeout=5)
    run_remote(ssh_host, ssh_user, ssh_key,
               "rm -f /tmp/failback_dump.sql && "
               "docker exec devops-learning-db-prod rm -f /tmp/failback_dump.sql",
               timeout=10)

    # ── Step 7: Remove standby.signal on primary ──
    step(7, total_steps, "Configuring primary as standalone")
    run_remote(ssh_host, ssh_user, ssh_key,
               f"sudo rm -f {pg_path}/standby.signal")

    # Write a CLEAN postgresql.auto.conf on primary (overwrite, NOT append)
    # This prevents the corruption caused by leftover replication entries
    primary_autoconf = write_clean_autoconf(f"{pg_path}/postgresql.auto.conf", mode="primary")
    # Escape content for remote shell — use heredoc for safety
    run_remote(ssh_host, ssh_user, ssh_key,
               f"sudo tee {pg_path}/postgresql.auto.conf > /dev/null << 'AUTOCONF_EOF'\n"
               f"{primary_autoconf}AUTOCONF_EOF")

    # Fix ownership
    run_remote(ssh_host, ssh_user, ssh_key,
               f"sudo chown -R 999:999 {pg_path}")

    # Validate the file we just wrote
    is_valid, details = validate_autoconf(
        f"{pg_path}/postgresql.auto.conf",
        is_remote=True, ssh_host=ssh_host, ssh_user=ssh_user, ssh_key=ssh_key)
    if is_valid:
        result_pass(f"Primary postgresql.auto.conf clean — {details}")
    else:
        result_warn(f"Primary auto.conf validation: {details}")
    result_pass("Primary configured as standalone")

    # ── Step 8: Start primary stack ──
    step(8, total_steps, "Starting primary application stack")
    ok, out, err = run_remote(
        ssh_host, ssh_user, ssh_key,
        f"cd {primary_compose} && "
        "docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d",
        timeout=120
    )
    if ok:
        result_pass("Primary stack starting")
    else:
        result_warn(f"Start output: {err}")

    # Wait for health
    print(f"  {C.YELLOW}Waiting for primary health check...{C.END}")
    primary_healthy = False
    for attempt in range(1, 21):
        try:
            resp = requests.get(config["primary"]["health_url"], timeout=10)
            if resp.status_code == 200:
                result_pass(f"Primary healthy! (attempt {attempt})")
                primary_healthy = True
                break
        except Exception:
            pass
        print(f"    Attempt {attempt}/20 — waiting 15s...")
        time.sleep(15)

    if not primary_healthy:
        result_fail("Primary failed health check after 20 attempts!")
        state.set_status("FAILED")
        return False

    # ── Step 9: Convert DR back to standby ──
    step(9, total_steps, "Converting DR back to standby mode")

    # Stop all DR containers and permanently destroy them (including ghost volumes/orphans)
    run_cmd(["sudo", "docker", "compose",
             "-f", f"{compose_path}/docker-compose.yml",
             "-f", f"{compose_path}/docker-compose.prod.yml",
             "-f", f"{compose_path}/docker-compose.dr.yml",
             "down", "-v", "--remove-orphans"], timeout=90)

    # Re-create replication slot on primary (if dropped)
    run_remote(ssh_host, ssh_user, ssh_key,
               "docker exec devops-learning-db-prod psql -U devops -d devops_learning -c "
               "\"SELECT pg_create_physical_replication_slot('dr_mumbai');\" 2>/dev/null || true")

    # Wipe DR data and re-sync
    run_cmd("sudo rm -rf /data/postgres/*", timeout=30)
    run_cmd("sudo chown $(whoami):$(whoami) /data/postgres", timeout=10)

    basebackup_ok, out, err = run_cmd([
        "pg_basebackup",
        "-h", ssh_host, "-p", "5432", "-U", "replicator",
        "-D", "/data/postgres",
        "--checkpoint=fast", "--slot=dr_mumbai",
        "--wal-method=stream", "--progress", "--verbose"
    ], timeout=600)

    if basebackup_ok:
        result_pass("DR data re-synced from primary")
    else:
        result_warn(f"pg_basebackup to DR: {err}")
        result_warn("Manual re-sync may be needed later — proceeding with standby config")

    # ── CRITICAL FIX: Write standby config using OVERWRITE, never append ──
    # pg_basebackup copies the primary's postgresql.auto.conf, which may
    # contain ALTER SYSTEM entries. We OVERWRITE it with clean standby config.
    # Using tee -a (append) here was the root cause of the corruption bug.

    # Create standby.signal
    run_cmd("sudo touch /data/postgres/standby.signal", timeout=5)

    # Write a CLEAN postgresql.auto.conf (OVERWRITE — not append!)
    standby_conf = write_clean_autoconf(
        "/data/postgres/postgresql.auto.conf",
        mode="standby",
        primary_host=ssh_host,
        repl_user="replicator",
        repl_pass="Admin@123",
        repl_slot="dr_mumbai"
    )
    # Use heredoc to safely write multi-line content without shell escaping issues
    run_cmd(
        f"sudo tee /data/postgres/postgresql.auto.conf > /dev/null << 'AUTOCONF_EOF'\n"
        f"{standby_conf}AUTOCONF_EOF",
        timeout=5
    )

    # Fix ownership (999 = postgres user inside the container)
    run_cmd("sudo chown -R 999:999 /data/postgres", timeout=10)
    run_cmd("sudo chmod 600 /data/postgres/postgresql.auto.conf", timeout=5)

    # Validate the file before starting PostgreSQL
    is_valid, details = validate_autoconf("/data/postgres/postgresql.auto.conf")
    if is_valid:
        result_pass(f"DR postgresql.auto.conf validated — {details}")
    else:
        result_fail(f"DR postgresql.auto.conf INVALID: {details}")
        log.error("Auto.conf validation failed — attempting re-write")
        # Emergency re-write: use Python directly to avoid shell escaping
        try:
            with open("/tmp/pg_autoconf_fix.conf", "w") as f:
                f.write(standby_conf)
            run_cmd("sudo cp /tmp/pg_autoconf_fix.conf /data/postgres/postgresql.auto.conf", timeout=5)
            run_cmd("sudo chown 999:999 /data/postgres/postgresql.auto.conf", timeout=5)
            run_cmd("sudo chmod 600 /data/postgres/postgresql.auto.conf", timeout=5)
            run_cmd("rm -f /tmp/pg_autoconf_fix.conf", timeout=5)
            result_pass("Re-wrote postgresql.auto.conf via direct file write")
        except Exception as e:
            result_fail(f"Emergency re-write also failed: {e}")

    # Start DR PG in standby mode
    run_cmd(["sudo", "docker", "compose",
             "-f", f"{compose_path}/docker-compose.yml",
             "-f", f"{compose_path}/docker-compose.prod.yml",
             "-f", f"{compose_path}/docker-compose.dr.yml",
             "up", "-d", "postgres"], timeout=60)

    time.sleep(10)
    ok, out, err = run_cmd(
        "sudo docker logs devops-learning-db-dr --tail 5 2>&1 | grep -c 'streaming WAL'",
        timeout=10
    )
    if ok and out.strip() != "0":
        result_pass("DR PostgreSQL streaming from primary")
    else:
        result_warn("DR streaming not confirmed — check logs manually")

    # ── Step 10: Reset auto-failover ──
    step(10, total_steps, "Resuming auto-failover monitoring")
    state.set_status("MONITORING")
    state.reset_failure()
    state.add_history("FAILBACK_COMPLETE")
    result_pass("Auto-failover reset to MONITORING")

    # ── Final Summary ──
    banner("FAILBACK COMPLETE ✅", "🎉")
    print(f"  {C.GREEN}{C.BOLD}Primary is now serving traffic{C.END}")
    print(f"  {C.GREEN}  URL: {config['primary']['health_url'].replace('/api/health', '')}{C.END}")
    print(f"  {C.GREEN}  DR:  Standby mode (streaming from primary){C.END}")
    print()
    print(f"  {C.YELLOW}Verify:{C.END}")
    print(f"    curl {config['primary']['health_url']}")
    print(f"    python3 auto_failover.py --status")
    print()

    log.critical("✅ FAILBACK COMPLETE — Primary is serving traffic")
    return True

