def run_cmd(cmd, timeout=60, check=False):
    """Run a shell command and return (success, stdout, stderr)."""
    try:
        result = subprocess.run(
            cmd, capture_output=True, text=True,
            timeout=timeout, shell=isinstance(cmd, str)
        )
        return result.returncode == 0, result.stdout.strip(), result.stderr.strip()
    except subprocess.TimeoutExpired:
        return False, "", "Command timed out"
    except Exception as e:
        return False, "", str(e)


def write_clean_autoconf(path, mode="primary", primary_host="", repl_user="replicator",
                         repl_pass="Admin@123", repl_slot="dr_mumbai"):
    """
    Generate a clean postgresql.auto.conf content string.
    This MUST be written via overwrite (tee), NEVER appended (tee -a).

    Args:
        path: Where to write the file (local or used in remote command)
        mode: 'primary' for standalone, 'standby' for streaming replication
        primary_host: IP of the primary server (required for standby mode)
        repl_user: Replication username
        repl_pass: Replication password
        repl_slot: Replication slot name

    Returns:
        The full content string to write to postgresql.auto.conf
    """
    timestamp = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    header = (
        "# Do not edit this file manually!\n"
        "# It will be overwritten by the ALTER SYSTEM command.\n"
        f"# Last updated by auto_failback.py at {timestamp}\n"
    )

    if mode == "standby":
        content = (
            f"{header}\n"
            f"primary_conninfo = 'host={primary_host} port=5432 user={repl_user} password={repl_pass} application_name={repl_slot}'\n"
            f"primary_slot_name = '{repl_slot}'\n"
        )
    else:
        # Primary mode — clean file with only the header
        content = f"{header}"

    return content


def validate_autoconf(path, is_remote=False, ssh_host="", ssh_user="", ssh_key=""):
    """
    Validate that postgresql.auto.conf is syntactically correct.
    Checks for common corruption patterns.

    Returns: (is_valid: bool, details: str)
    """
    if is_remote:
        ok, content, err = run_remote(ssh_host, ssh_user, ssh_key,
                                       f"cat {path}")
    else:
        ok, content, err = run_cmd(f"sudo cat {path}", timeout=10)

    if not ok:
        return False, f"Cannot read file: {err}"

    lines = content.strip().split("\n")
    issues = []

    for i, line in enumerate(lines, 1):
        stripped = line.strip()
        # Skip empty lines and comments
        if not stripped or stripped.startswith("#"):
            continue
        # Each non-comment line must be: key = value
        if "=" not in stripped:
            issues.append(f"Line {i}: missing '=' — '{stripped}'")
        # Check for duplicate entries (common corruption pattern)
        key = stripped.split("=", 1)[0].strip()
        duplicates = sum(1 for l in lines if l.strip().startswith(key + " ") or l.strip().startswith(key + "="))
        if duplicates > 1:
            issues.append(f"Line {i}: duplicate key '{key}' found {duplicates} times")

    if issues:
        return False, "; ".join(issues)
    return True, f"Valid — {len(lines)} lines, {len([l for l in lines if l.strip() and not l.strip().startswith('#')])} settings"


def run_remote(host, user, key_path, command, timeout=60):
    """Run command on remote host via SSH."""
    ssh_cmd = [
        "ssh", "-o", "ConnectTimeout=10",
        "-o", "StrictHostKeyChecking=no",
        "-o", "BatchMode=yes"
    ]
    if key_path:
        ssh_cmd.extend(["-i", key_path])
    ssh_cmd.extend([f"{user}@{host}", command])

    return run_cmd(ssh_cmd, timeout=timeout)


def banner(text, char="═"):
    width = 55
    print(f"\n{C.BOLD}{char * width}{C.END}")
    print(f"{C.BOLD}  {text}{C.END}")
    print(f"{C.BOLD}{char * width}{C.END}\n")


def step(number, total, description):
    print(f"\n{C.BLUE}{C.BOLD}[{number}/{total}]{C.END} {description}")
    log.info(f"Step {number}/{total} — {description}")


def result_pass(msg):
    print(f"  {C.GREEN}✅ {msg}{C.END}")
    log.info(f"  PASS: {msg}")


def result_fail(msg):
    print(f"  {C.RED}❌ {msg}{C.END}")
    log.error(f"  FAIL: {msg}")


def result_warn(msg):
    print(f"  {C.YELLOW}⚠️  {msg}{C.END}")
    log.warning(f"  WARN: {msg}")


def confirm(prompt):
    """Ask for confirmation. Returns True if confirmed."""
    response = input(f"\n{C.YELLOW}{prompt} (yes/no): {C.END}").strip().lower()
    return response in ("yes", "y")

